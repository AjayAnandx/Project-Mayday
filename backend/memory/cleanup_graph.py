"""One-time Brain V2 (P1) clean-up of memory_graph.json.

    python -m backend.memory.cleanup_graph            # dry run: prints what would change
    python -m backend.memory.cleanup_graph --apply    # backs up, then rewrites the graph

Stop the Mayday backend first (NSSM service / dev server): a running backend keeps
the graph in memory and would write the old version back on its next save.

Rules (each one is listed in the report with counts and examples):
  1. test-leftover projects: not in projects.json AND named like a test run
  2. duplicate nodes: same type + same label (case/prefix-insensitive) -> merged,
     edges re-pointed to the survivor (the one with most edges)
  3. email nodes: removed (they live in Gmail + the operation log)
  4. junk "preferences": tool output / error strings removed; real build rules
     retyped to `build_preference`; the saved coordinates retyped to `location`
  5. roles / orgs stored as people ("person:ML Engineer"): removed, or retyped to
     `organization` when listed in ORG_LABELS
  6. cascade: nodes left with no edges that were only connected to removed nodes
Pure function `plan_cleanup(graph, project_names)` is unit-tested; the CLI is I/O.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import socket
import sys
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path

from backend.core.evolution import _is_rule_text

REPO = Path(__file__).resolve().parents[2]
ROLE_RE = re.compile(r"\b(engineer|developer|manager|intern|designer|scientist|analyst|founder|ceo|cto)\b", re.I)
TEST_PERSON_RE = re.compile(r"test\s*person|xyz$", re.I)
ORG_LABELS = {"quantumscripts"}
# Names generated by test/benchmark runs (often with a numeric suffix). Orphan
# projects are only removed when they match this; real past projects that are no
# longer in projects.json are kept and listed.
TEST_PROJECT_RE = re.compile(
    r"^(seed|bench|benchproj|benchseed|trustproj|trusttaskproj|trust-test-proj|trust-check"
    r"|website|websitebench|taskapp|totally different name|replayproj|checkpointproj"
    r"|parentchildproj|parent-child-test|artifactproj|hookproj|ctxproj|testreloadcheck"
    r"|test-resilient-xyz|force-dup-proj|conc|fullbuildsite|fullbuildbench|batchtest"
    r"|test proj export|porttest)[-\d.]*$", re.I)
_PREFIXES = ("person:", "project:", "concept:", "tag:", "research:")


def _norm(label: str) -> str:
    l = (label or "").strip().lower()
    for p in _PREFIXES:
        if l.startswith(p):
            l = l[len(p):]
    return re.sub(r"\s+", " ", l).strip()


def plan_cleanup(graph: dict, project_names: set[str], aliases: dict[str, str] | None = None) -> dict:
    """Return {'graph': new_graph, 'report': {rule: {count, examples}}}. Does not mutate input.

    ``aliases``: {"Jon Smyth": "Jon Smith"} renames the misspelt name on
    every node (prefix kept) and merges it into the correct one, for any type."""
    nodes = {n["id"]: json.loads(json.dumps(n)) for n in graph.get("nodes", [])}
    edges = [dict(e) for e in graph.get("edges", [])]
    project_names = {p.strip().lower() for p in project_names}
    report: dict[str, dict] = defaultdict(lambda: {"count": 0, "examples": []})
    removed: set[str] = set()
    alias_map = {_norm(k): v.strip() for k, v in (aliases or {}).items()}
    aliased: set[str] = set()

    def note(rule, label):
        r = report[rule]
        r["count"] += 1
        if len(r["examples"]) < 6:
            r["examples"].append(label[:70])

    def remove(nid, rule):
        if nid in nodes and nid not in removed:
            removed.add(nid)
            note(rule, nodes[nid]["label"])

    for nid, n in nodes.items():
        new_name = alias_map.get(_norm(n["label"]))
        if new_name:
            low = n["label"].lower()
            prefix = next((p for p in _PREFIXES if low.startswith(p)), "")
            n["label"] = n["label"][:len(prefix)] + new_name
            aliased.add(nid)
        t, label, props = n["type"], n["label"], n.get("properties", {})
        if t == "project" and project_names and _norm(label) not in project_names:
            if TEST_PROJECT_RE.match(_norm(label)):
                remove(nid, "1 test-leftover project")
            else:
                note("1 kept: project not in projects.json", label)
        elif t == "email":
            remove(nid, "3 email node")
        elif t == "preference":
            if props.get("lat") and props.get("lon"):
                n["type"] = "location"
                props["kind"] = "user_location"
                note("4 location retyped", label)
            elif props.get("rule") is not None:
                if _is_rule_text(props.get("rule", "")):
                    n["type"] = "build_preference"
                    note("4 build rule retyped", label)
                else:
                    remove(nid, "4 junk preference (tool output)")
        elif t == "person":
            base = _norm(label)
            if base in ORG_LABELS:
                n["type"] = "organization"
                n["label"] = re.sub(r"^person:", "", label, flags=re.I).strip()
                note("5 org retyped", label)
            elif ROLE_RE.search(base) or TEST_PERSON_RE.search(base):
                remove(nid, "5 role/test stored as person")

    # 2. merge duplicates (after retyping, among survivors)
    degree = Counter()
    for e in edges:
        degree[e["source"]] += 1
        degree[e["target"]] += 1
    groups: dict[tuple, list[str]] = defaultdict(list)
    # Only real-world entities are merged. Generic concepts such as a note file
    # "research.md" share a label across projects but are different things.
    mergeable = {"person", "project", "organization", "place", "location", "research", "user"}
    for nid, n in nodes.items():
        if nid not in removed:
            groups[(n["type"], _norm(n["label"]))].append(nid)
    redirect: dict[str, str] = {}
    for (_t, _l), ids in groups.items():
        if len(ids) < 2 or not _l:
            continue
        if _t not in mergeable and not aliased.intersection(ids):
            continue
        # survivor: most edges, then the prefixed/canonical label, then id
        ids.sort(key=lambda i: (-degree[i], not nodes[i]["label"].lower().startswith(_PREFIXES), i))
        keep = ids[0]
        for dup in ids[1:]:
            redirect[dup] = keep
            for k, v in nodes[dup].get("properties", {}).items():
                nodes[keep].setdefault("properties", {}).setdefault(k, v)
            remove(dup, "2 duplicate merged")

    # rewrite edges: redirect merged, drop edges touching removed nodes, dedupe
    touched_by_removed: set[str] = set()
    new_edges, seen = [], set()
    for e in edges:
        # merged duplicates are redirected to their survivor, which is never removed
        s, t = redirect.get(e["source"], e["source"]), redirect.get(e["target"], e["target"])
        if s in removed or t in removed or s == t:
            touched_by_removed.update(x for x in (s, t) if x not in removed)
            note("edges dropped", e.get("relation", ""))
            continue
        fp = (s, t, e.get("relation"))
        if fp in seen:
            note("edges dropped", "duplicate " + e.get("relation", ""))
            continue
        seen.add(fp)
        new_edges.append({**e, "source": s, "target": t})

    # 6. cascade: orphaned by the removals, and not something the user owns
    still = Counter()
    for e in new_edges:
        still[e["source"]] += 1
        still[e["target"]] += 1
    keep_types = {"user", "person", "event", "todo", "document", "research", "location",
                  "organization", "place", "favorite_song", "conversation"}
    for nid in touched_by_removed:
        if nid not in removed and still[nid] == 0 and nodes[nid]["type"] not in keep_types:
            remove(nid, "6 orphaned by removals")

    out_nodes = [n for nid, n in nodes.items() if nid not in removed]
    report_out = {k: dict(v) for k, v in sorted(report.items())}
    return {"graph": {**graph, "nodes": out_nodes, "edges": new_edges},
            "report": report_out,
            "before": {"nodes": len(nodes), "edges": len(edges)},
            "after": {"nodes": len(out_nodes), "edges": len(new_edges)}}


def _project_names(path: Path) -> set[str]:
    if not path.exists():
        return set()
    data = json.loads(path.read_text(encoding="utf-8"))
    items = data if isinstance(data, list) else data.get("projects", data)
    if isinstance(items, dict):
        items = list(items.values())
    return {str(p.get("name", "")).strip().lower() for p in items if isinstance(p, dict) and p.get("name")}


def _backend_running() -> list[int]:
    up = []
    for port in (8771, 8772):
        with socket.socket() as s:
            s.settimeout(0.3)
            if s.connect_ex(("127.0.0.1", port)) == 0:
                up.append(port)
    return up


def main(argv=None) -> int:
    from backend.core.config import load_config
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--force", action="store_true", help="apply even if a backend is listening")
    ap.add_argument("--merge", action="append", default=[], metavar="WRONG=RIGHT",
                    help='merge a misspelt name, e.g. --merge "Jon Smyth=Jon Smith"')
    a = ap.parse_args(argv)

    cfg = load_config()
    gpath = Path(cfg.get("memory", {}).get("graph_path", "memory_graph.json"))
    gpath = gpath if gpath.is_absolute() else REPO / gpath
    ppath = Path(cfg.get("data", {}).get("projects_path", "projects.json"))
    ppath = ppath if ppath.is_absolute() else REPO / ppath
    names = _project_names(ppath)
    if not names:
        print(f"projects.json not found or empty at {ppath}; project rule disabled")

    # Operate on the SQLite store once it exists (backend: sqlite), else on the JSON.
    store = None
    mem = cfg.get("memory", {}) or {}
    if str(mem.get("backend", "json")).lower() == "sqlite":
        dbp = Path(mem.get("db_path") or gpath.with_name("brain.db"))
        dbp = dbp if dbp.is_absolute() else gpath.parent / dbp
        if dbp.exists():
            from backend.brain.store import BrainStore
            store = BrainStore(dbp)
            if store.is_empty():
                store = None
    if store is not None:
        graph = store.export_graph()   # also primes the sync cache
        gpath = store.path
    else:
        graph = json.loads(gpath.read_text(encoding="utf-8"))
    aliases = dict(m.split("=", 1) for m in a.merge if "=" in m)
    res = plan_cleanup(graph, names, aliases)
    w = sys.stdout.write
    w(f"graph: {gpath}\nnodes {res['before']['nodes']} -> {res['after']['nodes']}, "
      f"edges {res['before']['edges']} -> {res['after']['edges']}\n\n")
    for rule, r in res["report"].items():
        w(f"{rule}: {r['count']}\n")
        for ex in r["examples"]:
            w(f"    {ex!r}\n")
    if not a.apply:
        w("\nDry run. Re-run with --apply (stop the backend first).\n")
        return 0
    up = _backend_running()
    if up and not a.force:
        w(f"\nRefusing: a backend is listening on {up}. Stop it first, or pass --force.\n")
        return 2
    if store is not None:
        backup = store.backup(gpath.with_name(f"brain.pre-cleanup-{datetime.now():%Y%m%d-%H%M%S}.db"))
        store.import_graph(res["graph"], source="cleanup_graph")
        w(f"\nApplied to {gpath}. Backup: {backup}\n")
        return 0
    backup = gpath.with_name(f"memory_graph.pre-cleanup-{datetime.now():%Y%m%d-%H%M%S}.json")
    shutil.copy2(gpath, backup)
    tmp = gpath.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(res["graph"], indent=2, ensure_ascii=False), encoding="utf-8")
    tmp.replace(gpath)
    w(f"\nApplied. Backup: {backup}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
